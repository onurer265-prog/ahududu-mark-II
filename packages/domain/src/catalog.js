/** EAN-13 kontrol hanesi ekler (12 hane → 13 hane). */
export function ean13(d12) {
  const sum = [...d12].reduce((a, c, i) => a + Number(c) * (i % 2 ? 3 : 1), 0);
  return d12 + ((10 - (sum % 10)) % 10);
}

